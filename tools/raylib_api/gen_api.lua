--- @module gen_raylib_cdef
--- @file tools/gen_raylib_cdef.lua
--- @description Generates src/engine/backend/raylib/ffi_cdef.lua from the raylib API definition. Run from the project root: luajit tools/gen_raylib_cdef.lua [api_path]

--- @section Constants

local SRC = arg[1] or "tools/raylib_api/raylib.lua"
local OUT = "src/engine/backend/raylib/ffi.lua"

--- @section Source Loading

--- Reads an entire file from disk
--- @param path string File path
--- @return string contents Raw file contents
local function read(path)
    local file = assert(io.open(path, "rb"))
    local contents = file:read("*a")
    file:close()
    return contents
end

--- Escapes any unescaped double quote inside a description's inner text
--- @param inner string Text between the opening and closing quote of a description
--- @return string escaped Text with every inner quote escaped
local function escape_quotes(inner)
    return (inner:gsub('(\\*)"', function(slashes)
        if #slashes % 2 == 0 then return slashes .. '\\"' end
        return slashes .. '"'
    end))
end

-- The source has unescaped quotes inside some single-line description strings, so repair them line by line
local source = read(SRC):gsub("[^\n]+", function(line)
    local pre, inner, post = line:match('^(%s*description = ")(.*)(",?%s*)$')
    if pre then return pre .. escape_quotes(inner) .. post end
end)

local api = assert(loadstring(source, "=raylib_api"))()

local version = "unknown"
for _, define in ipairs(api.defines) do
    if define.name == "RAYLIB_VERSION" then version = tostring(define.value) end
end

--- @section Output Helpers

local buffer = {}

--- Appends a line to the output buffer
--- @param line string Line to append
local function add(line)
    buffer[#buffer + 1] = line
end

--- Formats a description as a trailing C++ style comment
--- @param description string|nil Description text
--- @return string comment Comment prefixed with a space, or empty string when there is no description
local function note(description)
    if not description or description == "" then return "" end
    description = description:gsub("[\r\n]+", " "):gsub("\\+$", "")
    return " // " .. description
end

--- Formats a description as a full comment line above a declaration
--- @param description string|nil Description text
--- @return string|nil comment Comment line, or nil when there is no description
local function note_above(description)
    if not description or description == "" then return nil end
    return (note(description):gsub("^ ", ""))
end

--- Joins parameter types into a C parameter list
--- @param params table|nil Array of { type, name } parameter entries
--- @return string types Comma separated types, or "void" when there are none
local function param_types(params)
    local types = {}
    for _, param in ipairs(params or {}) do
        types[#types + 1] = param.type
    end
    return #types > 0 and table.concat(types, ", ") or "void"
end

--- Appends a blank separator and optional header comment to a line list
--- @param lines table Line list being built
--- @param index number Position of the entry (separator is skipped for the first)
--- @param description string|nil Description for the header comment
local function begin_entry(lines, index, description)
    if index > 1 then lines[#lines + 1] = "" end
    local header = note_above(description)
    if header then lines[#lines + 1] = header end
end

--- Writes one `ffi.cdef` block under a section header
--- @param title string Section title
--- @param lines table Declaration lines
local function section(title, lines)
    local body = table.concat(lines, "\n")
    assert(not body:find("]]", 1, true), "cdef chunk '" .. title .. "' contains ]]")

    add("--- @section " .. title)
    add("")
    add("_ffi.cdef[[")
    add(body)
    add("]]")
    add("")
end

--- @section Generation

add("--- @module ffi")
add("--- @file " .. OUT)
add("--- @description C declarations for raylib " .. version .. ".")
add("--- GENERATED by tools/raylib_api/gen_api.lua. Do not edit.")
add("")
add("--- @section Imports")
add("")
add('local _ffi = require("ffi")')
add("")

-- Forward declarations, so structs and aliases can reference each other regardless of order
do
    local lines = {
        "typedef struct rAudioBuffer rAudioBuffer; // Opaque, used by pointer only",
        "typedef struct rAudioProcessor rAudioProcessor; // Opaque, used by pointer only",
    }
    for _, struct in ipairs(api.structs) do
        lines[#lines + 1] = ("typedef struct %s %s;"):format(struct.name, struct.name)
    end
    section("Forward Declarations", lines)
end

-- Aliases
do
    local lines = {}
    for _, alias in ipairs(api.aliases) do
        lines[#lines + 1] = ("typedef %s %s;%s"):format(alias.type, alias.name, note(alias.description))
    end
    section("Aliases", lines)
end

-- Structs
do
    local lines = {}
    for index, struct in ipairs(api.structs) do
        begin_entry(lines, index, struct.description)
        lines[#lines + 1] = ("struct %s {"):format(struct.name)
        for _, field in ipairs(struct.fields) do
            -- Array sizes arrive inside the type ("float[4]"), so move them after the name
            local base, size = field.type:match("^(.-)(%[%d+%])$")
            if base then
                lines[#lines + 1] = ("    %s %s%s;%s"):format(base, field.name, size, note(field.description))
            else
                lines[#lines + 1] = ("    %s %s;%s"):format(field.type, field.name, note(field.description))
            end
        end
        lines[#lines + 1] = "};"
    end
    section("Structs", lines)
end

-- Enums
do
    local lines = {}
    for index, enum in ipairs(api.enums) do
        begin_entry(lines, index, enum.description)
        lines[#lines + 1] = "typedef enum {"
        for _, value in ipairs(enum.values) do
            lines[#lines + 1] = ("    %s = %d,%s"):format(value.name, value.value, note(value.description))
        end
        lines[#lines + 1] = ("} %s;"):format(enum.name)
    end
    section("Enums", lines)
end

-- Callbacks (function pointer typedefs)
do
    local lines = {}
    for _, callback in ipairs(api.callbacks) do
        lines[#lines + 1] = ("typedef %s (*%s)(%s);%s"):format(
            callback.returnType, callback.name, param_types(callback.params), note(callback.description))
    end
    section("Callbacks", lines)
end

-- Functions
do
    local lines = {}
    for _, fn in ipairs(api.functions) do
        lines[#lines + 1] = ("%s %s(%s);%s"):format(
            fn.returnType, fn.name, param_types(fn.params), note(fn.description))
    end
    section("Functions", lines)
end

-- Small rlgl state surface needed by model transparency. Keep generated bindings reproducible.
section("Render State Functions", {
    "void rlDrawRenderBatchActive(void);",
    "void rlDisableDepthMask(void);",
    "void rlEnableDepthMask(void);",
    "void rlDisableBackfaceCulling(void);",
    "void rlEnableBackfaceCulling(void);",
})

add(([[
--- @section Library Binding Loading

local ok, raylib_lib = pcall(_ffi.load, "vendor/raylib/lib/raylib")
if not ok then
    raylib_lib = _ffi.load("raylib")
end

return {
    ffi = _ffi,
    lib = raylib_lib,
    version = %q,
    Color = _ffi.typeof("Color"),
}]]):format(version))

--- @section Output

local file = assert(io.open(OUT, "wb"))
file:write(table.concat(buffer, "\n"), "\n")
file:close()

print(("raylib %s -> %s"):format(version, OUT))